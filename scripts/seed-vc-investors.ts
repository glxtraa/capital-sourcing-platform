async function main() {
  const { PrismaClient } = await import("@prisma/client");
  const { resolveDatabaseUrl } = await import("../src/lib/env");
  resolveDatabaseUrl();
  const db = new PrismaClient();

  console.log(`Seeding ${SEED_VC_INVESTORS.length} Startup VC Investors across 5 archetypes...`);

  for (const inv of SEED_VC_INVESTORS) {
    const { documentsRequired = [], keyContacts = [], ...investorData } = inv;
    const payload = {
      ...investorData,
      keyContactsJson: keyContacts,
      lastVerified: new Date(),
    };
    await db.startupInvestor.upsert({
      where: { id: inv.id },
      create: {
        ...payload,
        documentsRequired: {
          create: documentsRequired.map((doc) => ({
            code: doc.code,
            note: doc.note ?? null,
          })),
        },
      },
      update: {
        ...payload,
        documentsRequired: {
          deleteMany: {},
          create: documentsRequired.map((doc) => ({
            code: doc.code,
            note: doc.note ?? null,
          })),
        },
      },
    });
    console.log(`✓ Seeded ${inv.type}: ${inv.name} (${inv.id})`);
  }

  await db.$disconnect();
  console.log("Seed complete.");
}

if (process.argv[1]?.endsWith("seed-vc-investors.ts")) {
  main().catch((e) => {
    console.error("Seeding failed:", e);
    process.exit(1);
  });
}
